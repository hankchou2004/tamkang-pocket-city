"""Write landmarks/07-sports.js: the running track and the courts (OpenStreetMap leisure=track / pitch) and the two
campus sculptures (五虎碑, 里程碑) in plot metres, with the same projection as the Pocket City prep step.
  python tools/sports.py"""
import json, math, sys
sys.stdout.reconfigure(encoding='utf-8')
osm = json.load(open('work/osm.json', encoding='utf-8')); plot = json.load(open('work/plot.json', encoding='utf-8'))
lat0, lon0, rot, half = plot['lat'], plot['lon'], plot['rotation'], plot['size'] / 2
kx, ky = 111320 * math.cos(math.radians(lat0)), 110574
cr, sr = math.cos(math.radians(-rot)), math.sin(math.radians(-rot))
def P(lat, lon):
    x, y = (lon - lon0) * kx, (lat - lat0) * ky
    return [round(x * cr - y * sr, 2), round(x * sr + y * cr, 2)]
els = osm.get('elements', osm)
def ring(w): return [P(g['lat'], g['lon']) for g in (w.get('geometry') or [])]
def join(parts):   # stitch member ways end to end into closed rings
    parts = [p[:] for p in parts if p]; rings = []
    while parts:
        cur = parts.pop(0)
        while cur[0] != cur[-1] and parts:
            for i, q in enumerate(parts):
                if q[0] == cur[-1]: cur += q[1:]; parts.pop(i); break
                if q[-1] == cur[-1]: cur += q[::-1][1:]; parts.pop(i); break
            else: break
        rings.append(cur)
    return rings
inside = lambda r: all(abs(x) < half + 5 and abs(y) < half + 5 for x, y in r)

pitches, tracks = [], []
for e in els:
    t = e.get('tags', {})
    if e['type'] == 'way' and t.get('leisure') == 'pitch' and 'rugby' not in t.get('sport', ''):
        r = ring(e)
        if len(r) > 3 and inside(r): pitches.append({'sport': t.get('sport', ''), 'r': r[:-1] if r[0] == r[-1] else r})
    if e['type'] == 'relation' and t.get('leisure') == 'track':
        mem = [m for m in e['members'] if m['type'] == 'way']
        outs = join([ring(m) for m in mem if m.get('role') in ('outer', '')]); ins = join([ring(m) for m in mem if m.get('role') == 'inner'])
        for o in outs:
            if len(o) > 3 and inside(o): tracks.append({'outer': o[:-1] if o[0] == o[-1] else o, 'inner': [i[:-1] if i[0] == i[-1] else i for i in ins]})
sculpt = {}
for e in els:
    n = e.get('tags', {}).get('name')
    if n == '五虎碑' and e['type'] == 'node': sculpt['tigers'] = P(e['lat'], e['lon'])
    if n == '里程碑' and e['type'] == 'way': r = ring(e); sculpt['dolphin'] = [round(sum(p[0] for p in r) / len(r), 2), round(sum(p[1] for p in r) / len(r), 2)]

js = '''/* ====================== District 7: sports grounds and campus sculptures ======================
   Generated by tools/sports.py from OpenStreetMap (leisure=track / pitch; 五虎碑 node, 里程碑 way). Colours from the
   user's photos (淡江照片: 操場.jpg — a red running track round a grass field with goals; 網球場+書卷廣場.jpeg — red-orange
   tennis courts with green playing areas; 五虎碑雕塑.jpg — a bronze ring of five tigers on a granite pedestal beside the
   gym; 海豚雕塑.jpg — a bronze dolphin pair on a dark post in a round box hedge, the 海豚吉祥物里程碑).
   Line markings, goals and nets are simplified; the sculptures' proportions are read by eye. */
const SPORTS = ''' + json.dumps({'tracks': tracks, 'pitches': pitches, 'sculpt': sculpt}, ensure_ascii=False) + ''';
const COURT = { tennis: ['#c8694a', '#5f9a68'], basketball: ['#b9a88f', '#8fa6b8'], volleyball: ['#c8694a', '#d9a35a'], roller_skating: ['#b9b3ad', '#c7c1ba'], '': ['#b9a88f', '#a9b8a0'] };

function sportsGrounds() {
  const out = [];
  for (const t of SPORTS.tracks) out.push(obj(t.outer, .4, () => {
    let s = shape(atZ(ccw(t.outer), .16), '#b8553f', .4);                 // red running track
    for (const i of t.inner) s += shape(atZ(ccw(i), .2), '#8fbf6a', .4);   // the grass field
    return s;
  }));
  for (const p of SPORTS.pitches) out.push(obj(p.r, .4, () => {
    const [outer, inner] = COURT[p.sport] || COURT[''], r = ccw(p.r), c = avg(r);
    return shape(atZ(r, .17), outer, .35) + shape(atZ(toward(c, r, .78), .19), inner, 0) +
      edge([...toward(c, r, .78)[0], .2], [...toward(c, r, .78)[2], .2], '#f4efe2', .05);
  }));
  return out;
}

// 五虎碑: a granite pedestal and a bronze ring of five tigers
function fiveTigers() {
  const q = SPORTS.sculpt.tigers; if (!q) return null;
  const [x, y] = q, BRONZE = '#5a5148';
  return obj(rect(x, y, 3.4, 3.4), 6, () => {
    let s = solid(ccw(rect(x, y, 3.2, 2.4)), 0, .3, '#bdb4a7', '#cbc3b7') + solid(ccw(rect(x, y, 1.5, 1.1)), .3, 2.4, '#b6ada0', '#c4bcb0');
    for (let k = 0; k < 14; k++) { const a = k / 14 * Math.PI * 2; s += ball([x + Math.cos(a) * 1.05, y, 3.55 + Math.sin(a) * 1.05], .36, soft(BRONZE), .3); }
    return s;
  });
}

// 海豚吉祥物里程碑: a dark post in a round box hedge, a bronze dolphin pair on top
function dolphins() {
  const q = SPORTS.sculpt.dolphin; if (!q) return null;
  const [x, y] = q;
  return obj(rect(x, y, 7, 7), 6, () => {
    let s = '';
    for (let k = 0; k < 16; k++) { const a = k / 16 * Math.PI * 2; s += ball([x + Math.cos(a) * 2.6, y + Math.sin(a) * 2.6, .5], .6, soft('#6f9a55'), .3); }
    s += solid(ccw(rect(x, y, .5, .5)), 0, 3.2, '#3e3a37', '#4a4541');
    for (const [dx, dz, r] of [[-.2, 3.6, .3], [.05, 4.1, .27], [.3, 4.55, .2], [.35, 3.5, .26], [.5, 3.95, .22]]) s += ball([x + dx, y, dz], r, soft('#3f3d3b'), .3);
    return s;
  });
}

LANDMARKS.push(
  { name: '操場與球場', ids: [], build: sportsGrounds },
  { name: '五虎碑', ids: [], build: fiveTigers },
  { name: '海豚吉祥物里程碑', ids: [], build: dolphins },
);
'''
open('landmarks/07-sports.js', 'w', encoding='utf-8', newline='\n').write(js)
print('tracks', len(tracks), 'pitches', len(pitches), 'sculptures', sculpt)
